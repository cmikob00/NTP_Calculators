COL = {"HEU": "tab:blue", "HALEU": "tab:red"}


def period_curve(core, rho_abs, Lam):
    return np.array([asymptotic_period(r, core, Lam) for r in rho_abs])


def fig_period():
    rho = np.linspace(3.0e-4, 2.0e-2, 300)          # 30 pcm ... 2000 pcm
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(13, 5.5))
    for core, key, ls in ((HEU, "HEU", "-"), (HALEU, "HALEU", "--")):
        T = period_curve(core, rho, core.Lam)
        Tlo = period_curve(core, rho, core.Lam_range[0])
        Thi = period_curve(core, rho, core.Lam_range[1])
        lab = f"{core.name} (\u03b2={core.beta:.4f}, \u039b={core.Lam:.1e} s)"
        # Left panel: absolute reactivity (pcm). Right panel: dollars (each core's own beta).
        for ax, x in ((a1, rho * 1e5), (a2, rho / core.beta)):
            ax.semilogy(x, T, color=COL[key], ls=ls, lw=2.2, label=lab)
            ax.fill_between(x, np.minimum(Tlo, Thi), np.maximum(Tlo, Thi),
                            color=COL[key], alpha=0.12, lw=0)
        # PROMPT CRITICAL in pcm: rho = beta, i.e. beta * 1e5 pcm (HEU ~658, HALEU ~716).
        # Drawn as a vertical line, listed in the legend, AND written next to the line
        # so the value can be read straight off the plot.
        pc_pcm = core.beta * 1e5
        a1.axvline(pc_pcm, color=COL[key], ls=":", lw=1.8, alpha=0.9,
                   label=f"{key} prompt critical = {pc_pcm:.0f} pcm")
        # a1.text(pc_pcm, 2.0e-3, f" {pc_pcm:.0f} pcm", color=COL[key], rotation=90,
        #         ha="right" if key == "HEU" else "left", va="bottom",
        #         fontsize=10, fontweight="bold")
    a2.axvline(1.0, color="k", ls=":", label="prompt critical ($1)")
    a1.set(xlabel="Reactivity (pcm)", ylabel="Stable reactor period T (s)",
           title="Period vs. reactivity (pcm)", xlim=(0.0, 800), ylim=(1e-2, 1e3))
    a2.set(xlabel="Reactivity (dollars)", ylabel="Stable reactor period T (s)",
           title="Period vs. reactivity (dollars)", xlim=(0.0, 1.1), ylim=(1e-2, 1e3))
    for ax in (a1, a2):
        ax.grid(True, which="both", alpha=0.3)
        ax.legend(fontsize=8, loc="upper right")
    fig.suptitle("Asymptotic period (shaded = assumed \u039b sensitivity band)", y=1.0)
